const TABLES: Record<string, Table> = { en: EN, es: ES, tr: TR }

export function t(pt: string, values: Record<string, string | number> = {}): string {
  const text = TABLES[BASE]?.[pt] ?? pt
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in values ? String(values[name]) : all))
}

/** A value per language (chat lines, the simulated caption), Portuguese by default. */
export function pick<T>(byLang: { pt: T } & Partial<Record<'es' | 'en' | 'tr', T>>): T {
  return byLang[BASE as 'es' | 'en' | 'tr'] ?? byLang.pt
}
